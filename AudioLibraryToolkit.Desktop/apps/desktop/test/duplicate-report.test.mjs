import test from "node:test";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";

import { readDuplicateReport } from "../desktop/duplicate-report.mjs";

test("reads a schema-v1 report generated by the toolkit producer", async () => {
  const reportPath = fileURLToPath(new URL("./fixtures/duplicate-report-v1.json", import.meta.url));
  const report = await readDuplicateReport(reportPath);

  assert.equal(report.status, "completed");
  assert.equal(report.statistics.pairsReported, 1);
  assert.deepEqual(report.groups, [{
    albums: [
      "C:\\generated-fixture\\library\\first",
      "C:\\generated-fixture\\library\\second",
    ],
    pairs: [{
      album1: "C:\\generated-fixture\\library\\first",
      album2: "C:\\generated-fixture\\library\\second",
      confidence: "exact",
      evidence: [
        "same album name",
        "artists match",
        "1/1 tracks matched",
        "1 tracks with equal stored FLAC MD5",
      ],
    }],
  }]);
});
